import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { chromium } = process.env.PLAYWRIGHT_MODULE ? await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href) : await import('playwright');
const base = process.env.STUDIO_TEST_URL || 'http://127.0.0.1:3015';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  await page.goto(`${base}/tests/fixtures/x-tracking.html`);
  await page.getByText('Garden update across our projects').waitFor();
  await page.getByLabel('Sproutify', { exact: true }).check();
  await page.getByLabel('ATL Urban Farms', { exact: true }).check();
  await page.getByRole('button', { name: 'Save tags' }).click();
  await page.getByText('Project tags saved.').waitFor();
  await page.getByLabel('Filter by project').selectOption('atl');
  await page.getByText('Garden update across our projects').waitFor();
  await page.getByRole('button', { name: 'Daily metrics', exact: true }).click();
  await page.getByRole('cell', { name: '2026-10-19', exact: true }).waitFor();
  await page.getByLabel('Filter by project').selectOption('unassigned');
  await page.getByText('Nothing here yet.', { exact: false }).waitFor();
  await page.getByLabel('Filter by project').selectOption('');
  await page.getByLabel('Show X posts or mentions').selectOption('mentions');
  await page.getByText('@boilermanc When can we order seedlings?').waitFor();
  await page.getByLabel('Needs attention only').check();
  await page.getByRole('button', { name: 'Mark handled' }).click();
  await page.getByText('Nothing here yet.', { exact: false }).waitFor();
  await page.getByLabel('Needs attention only').uncheck();
  await page.getByRole('button', { name: 'Reopen mention' }).waitFor();
  await page.getByRole('button', { name: 'Sync now' }).click();
  await page.getByRole('alert').getByText(/rate limit/).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.getByRole('button', { name: 'Daily metrics', exact: true }).click();
  await page.getByRole('cell', { name: '2026-10-19', exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  if (process.env.X_SCREENSHOT) await page.screenshot({ path: process.env.X_SCREENSHOT, fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS X tracking browser: tags, filters, mention status, history, error state, mobile layout; no console errors.');
} finally { await browser.close(); }
